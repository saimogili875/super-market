"""ModelForm for admin-dashboard table management.

The qr_token is generated by the model default and is never user-editable
(IDOR defense), so it is intentionally excluded from the form.
"""
from django import forms

from .models import Table


class TableForm(forms.ModelForm):
    """Create/edit a dining table (number + active flag)."""

    class Meta:
        model = Table
        fields = ("number", "is_active")

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.fields["number"].widget.attrs.setdefault("class", "form-input")
